    async def fetch_holdings(self, top_n: int = 1000) -> list[dict[str, Any]]:
        """
        Asynchronously fetch ETF holdings.

        Args:
            top_n: Number of top holdings to return

        Returns:
            List of holding dictionaries sorted by weight
        """
        holdings = await asyncio.to_thread(self._fetch_holdings_sync)

        # Sort by weight descending and take top N
        holdings.sort(key=lambda x: x.get("weight", 0), reverse=True)
        return holdings[:top_n]

