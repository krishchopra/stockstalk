    def __init__(self, etf_symbol: str = "VTI") -> None:
        """
        Initialize the ETF holdings fetcher.

        Args:
            etf_symbol: The ETF ticker symbol (default: VTI)
        """
        self.etf_symbol = etf_symbol.upper()

    def _fetch_holdings_sync(self) -> list[dict[str, Any]]:
        """
        Synchronously fetch ETF holdings from Yahoo Finance.

        Returns:
            List of holding dictionaries with symbol and weight
        """
        try:
            ticker = yf.Ticker(self.etf_symbol)

            # Try to get holdings from the ETF
            # yfinance provides holdings via the 'funds_data' property for ETFs
            try:
                holdings_df = ticker.funds_data.top_holdings
                if holdings_df is not None and not holdings_df.empty:
                    holdings = []
                    for symbol, row in holdings_df.iterrows():
                        # Symbol is the index, weight is in the 'holdingPercent' column
                        if isinstance(symbol, str) and symbol:
                            weight = row.get("holdingPercent", row.iloc[0]) if len(row) > 0 else 0
                            holdings.append(
                                {
                                    "symbol": symbol.upper(),
                                    "weight": float(weight) if weight else 0,
                                }
                            )
                    return holdings
            except Exception as e:
                logger.debug(f"Could not fetch holdings via funds_data: {e}")

            # Fallback: Try the info dict
            info = ticker.info
            if "holdings" in info:
                return [
                    {
                        "symbol": h.get("symbol", "").upper(),
                        "weight": h.get("holdingPercent", 0),
                    }
                    for h in info["holdings"]
                    if h.get("symbol")
                ]

            logger.warning(
                f"Could not fetch live holdings for {self.etf_symbol}. "
                "Using curated VTI top holdings list."
            )
            return self._get_curated_vti_holdings()

        except Exception as e:
            logger.error(f"Error fetching {self.etf_symbol} holdings: {e}")
            return self._get_curated_vti_holdings()

